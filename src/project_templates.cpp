std::string GabProjectTemplates::sanitize_app_id(const std::string &name) {
  std::string out;
  for (char c : name) {
    if (std::isalnum(static_cast<unsigned char>(c)))
      out.push_back(static_cast<char>(std::tolower(static_cast<unsigned char>(c))));
    else if (c == '-' || c == '_')
      out.push_back('_');
  }
  if (out.empty())
    out = "app";
  if (std::isdigit(static_cast<unsigned char>(out.front())))
    out = "app_" + out;
  return out;
}

