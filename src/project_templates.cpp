using FileMap = std::vector<std::pair<std::string, std::string>>;

bool ensure_dir(const std::string &path, std::string &error) {
  std::error_code ec;
  fs::create_directories(path, ec);
  if (ec) {
    error = "Failed to create directory: " + path + " (" + ec.message() + ")";
    return false;
  }
  return true;
}

bool write_tree(const std::string &root, const FileMap &files, std::string &error) {
  for (const auto &item : files) {
    const fs::path full = fs::path(root) / item.first;
    if (!ensure_dir(full.parent_path().string(), error))
      return false;
    std::ofstream out(full);
    if (!out) {
      error = "Failed to write file: " + full.string();
      return false;
    }
    out << item.second;
  }
  return true;
}

std::string app_id(const GabProjectInfo &info) {
  return "org.example." + GabProjectTemplates::sanitize_app_id(info.name);
}

std::string readme(const std::string &name, const std::string &blurb,
                   const std::string &hint) {
  return "# " + name + "\n\n" + blurb +
         "\n\nGenerated by **Luma Builder**.\n\n## Build\n\n```bash\n" + hint +
         "\n```\n";
}

std::string desktop(const GabProjectInfo &info) {
  return "[Desktop Entry]\nName=" + info.name + "\nExec=" + info.name +
         "\nIcon=" + info.name +
         "\nTerminal=false\nType=Application\nCategories=GNOME;GTK;\n";
}

std::string meson_exec(const GabProjectInfo &info, const std::string &lang,
                       const std::string &src, const std::vector<std::string> &deps) {
  std::ostringstream o;
  o << "project('" << info.name << "', '" << lang << "',\n"
    << "  version: '0.1.0',\n"
    << "  meson_version: '>= 1.0.0',\n"
    << "  default_options: ['warning_level=2', '"
    << (lang == "cpp" ? "cpp_std=c++17" : "c_std=c11") << "'],\n)\n\n";
  if (!deps.empty()) {
    o << "deps = [\n";
    for (const auto &d : deps)
      o << "  dependency('" << d << "'),\n";
    o << "]\n\nexecutable('" << info.name << "',\n  '" << src
      << "',\n  dependencies: deps,\n  install: true,\n)\n";
  } else {
    o << "executable('" << info.name << "', '" << src << "', install: true)\n";
  }
  return o.str();
}

std::string meson_hint(const GabProjectInfo &info) {
  return "meson setup build && meson compile -C build && ./build/" + info.name;
}

std::string cmake_hint(const GabProjectInfo &info) {
  return "cmake -S . -B build && cmake --build build && ./build/" + info.name;
}

void add_gui_meta(FileMap &files, const GabProjectInfo &info, const std::string &blurb) {
  files.emplace_back("data/" + info.name + ".desktop", desktop(info));
  files.emplace_back("README.md", readme(info.name, blurb, meson_hint(info)));
}

std::string main_c_wrap(const GabProjectInfo &info, bool adw, const std::string &extras,
                        const std::string &activate_body) {
  std::ostringstream o;
  o << (adw ? "#include <adwaita.h>\n" : "#include <gtk/gtk.h>\n") << extras << "\n"
    << "static void\nactivate (GtkApplication *app, gpointer user_data)\n{\n"
    << "  (void) user_data;\n"
    << activate_body << "}\n\n"
    << "int\nmain (int argc, char **argv)\n{\n";
  if (adw)
    o << "  AdwApplication *app = adw_application_new (\"" << app_id(info)
      << "\", G_APPLICATION_DEFAULT_FLAGS);\n";
  else
    o << "  GtkApplication *app = gtk_application_new (\"" << app_id(info)
      << "\", G_APPLICATION_DEFAULT_FLAGS);\n";
  o << "  g_signal_connect (app, \"activate\", G_CALLBACK (activate), NULL);\n"
    << "  return g_application_run (G_APPLICATION (app), argc, argv);\n}\n";
  return o.str();
}

std::string main_cpp_wrap(const GabProjectInfo &info, bool adw,
                          const std::string &activate_body) {
  std::ostringstream o;
  o << (adw ? "#include <adwaita.h>\n\n" : "#include <gtk/gtk.h>\n\n")
    << "static void activate(GtkApplication *app, gpointer) {\n"
    << activate_body << "}\n\n"
    << "int main(int argc, char **argv) {\n";
  if (adw)
    o << "  auto *app = adw_application_new(\"" << app_id(info)
      << "\", G_APPLICATION_DEFAULT_FLAGS);\n";
  else
    o << "  auto *app = gtk_application_new(\"" << app_id(info)
      << "\", G_APPLICATION_DEFAULT_FLAGS);\n";
  o << "  g_signal_connect(app, \"activate\", G_CALLBACK(activate), nullptr);\n"
    << "  return g_application_run(G_APPLICATION(app), argc, argv);\n}\n";
  return o.str();
}

